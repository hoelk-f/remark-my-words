import assert from 'node:assert/strict';
import { build } from 'esbuild';
const result = await build({entryPoints:['src/canvas-model.ts'],bundle:true,write:false,format:'esm',platform:'node'});
const {updateCanvas,arrangeCanvas,readCanvas}=await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].contents).toString('base64')}`);
const pages=[{width:800,height:1100},{width:1200,height:600},{width:800,height:1000}];
const style=()=>({label:'Note',hex:'#f4d653',color:'yellow',icon:'sticky-note'});
const source={version:2,pdfPath:'Folder/Ä & B.pdf',notes:'Untouched',annotations:Array.from({length:14},(_,i)=>({id:`annotation-${i}`,page:i<12?1:3,category:'note',text:`Quote ${i}`,title:`Title ${i}`,comment:'Long paragraph. '.repeat(i===0?160:6),tags:['Test'],quads:[{x:20,y:300,w:100,h:20}],createdAt:1,updatedAt:1}))};
const snapshot=structuredClone(source);
const data=updateCanvas(null,source,pages,style,'Test & vault');
assert.deepEqual(source,snapshot,'Canvas creation does not modify annotations');
assert.equal(data.nodes.length,17);
assert.equal(data.edges.length,14);
assert.deepEqual(data.nodes.filter(n=>n.type==='file').map(n=>n.subpath),['#page=1','#page=2','#page=3']);
assert.deepEqual(readCanvas(JSON.stringify(data),source.pdfPath),data);
const overlap=(a,b)=>a.x<b.x+b.width&&a.x+a.width>b.x&&a.y<b.y+b.height&&a.y+a.height>b.y;
for(let i=0;i<data.nodes.length;i++)for(let j=i+1;j<data.nodes.length;j++)assert.equal(overlap(data.nodes[i],data.nodes[j]),false,'Every page and comment has a nonoverlapping slot');
const files=data.nodes.filter(n=>n.type==='file');
assert.ok(files[1].y>files[0].y+files[0].height,'Long comments increase the next page offset');
const edited=data.nodes.find(n=>n.remarkMyWords?.annotation==='annotation-0');
edited.text='My native edit';edited.x=-2500;edited.y=800;edited.width=700;edited.height=1800;
const second=data.nodes.find(n=>n.remarkMyWords?.annotation==='annotation-1');
second.x=1900;second.y=55;
source.annotations[0].comment='Changed source';source.annotations[1].comment='Updated source';
data.nodes.push({id:'group',type:'group',label:'My group',x:-2600,y:750,width:900,height:1900,custom:'Keep'});
data.nodes.push({id:'extra',type:'text',x:8000,y:0,width:400,height:200,text:'Independent card'});
data.edges.push({id:'custom-edge',fromNode:edited.id,toNode:'extra',label:'Keep this edge'});
const refreshed=updateCanvas(data,source,pages,style,'Test & vault');
assert.equal(refreshed.nodes.find(n=>n.id===edited.id).text,'My native edit','Keep native text on refresh');
assert.equal(refreshed.nodes.find(n=>n.id===edited.id).x,-2500,'Keep manual positions');
assert.ok(refreshed.nodes.find(n=>n.id===second.id).text.includes('Updated source'),'Refresh unedited generated text');
const arranged=arrangeCanvas(refreshed);
assert.equal(arranged.nodes.find(n=>n.id===edited.id).width,700,'Respect native card resizing');
assert.equal(arranged.nodes.find(n=>n.id==='extra').x,8000,'Do not move unrelated cards');
assert.equal(arranged.edges.find(e=>e.id==='custom-edge').label,'Keep this edge');
const group=arranged.nodes.find(n=>n.id==='group'), member=arranged.nodes.find(n=>n.id===edited.id);
assert.equal(group.custom,'Keep');assert.ok(member.x>group.x&&member.y>group.y&&member.x+member.width<group.x+group.width&&member.y+member.height<group.y+group.height,'Group still contains its moved member');
assert.deepEqual(arrangeCanvas(arranged),arranged,'Rearrange is stable');
const removed=refreshed.nodes.find(n=>n.remarkMyWords?.annotation==='annotation-2');
refreshed.nodes=refreshed.nodes.filter(n=>n.id!==removed.id);refreshed.edges=refreshed.edges.filter(e=>e.toNode!==removed.id);
assert.ok(!updateCanvas(refreshed,source,pages,style,'Test').nodes.some(n=>n.remarkMyWords?.annotation==='annotation-2'),'Native deletion is not undone on refresh');
source.annotations=source.annotations.filter(a=>a.id!=='annotation-0'&&a.id!=='annotation-1');
const deleted=updateCanvas(refreshed,source,pages,style,'Test');
assert.ok(!deleted.nodes.some(n=>n.id===second.id),'Remove unchanged cards when source comment is deleted');
assert.equal(deleted.nodes.find(n=>n.id===edited.id).text,'My native edit','Keep edited cards after source deletion');
assert.equal(deleted.nodes.find(n=>n.id===edited.id).remarkMyWords,undefined);
for(const invalid of ['{}','{broken',JSON.stringify({...data,nodes:[{id:'invalid',x:0,y:0,width:-1,height:3}]}),JSON.stringify({...data,remarkMyWords:{...data.remarkMyWords,version:2}})])assert.throws(()=>readCanvas(invalid));
assert.throws(()=>readCanvas(JSON.stringify(data),'Different.pdf'),'Never overwrite an unrelated canvas');
console.log('PASS: native canvas page layout, mixed page sizes, long comments, native edits/deletions, group preservation, roundtrip and invalid data protection');
