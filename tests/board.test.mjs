import assert from 'node:assert/strict';
import {build} from 'esbuild';
const result = await build({entryPoints:['src/board-model.ts'],bundle:true,write:false,format:'esm'});
const {emptyLayout,ensureLayout,arrangeLayout,readLayout,LayoutHistory,snappedDelta,cleanLayout} = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
const sizes=[{width:800,height:1100},{width:1000,height:600}];
const annotations=Array.from({length:8},(_,i)=>({id:`a${i}`,page:i<6?1:2,text:'Passage',comment:'Comment',quads:[{x:10,y:20,w:40,h:20}],position:{x:-420,y:50+i*260}}));
const original=structuredClone(annotations), layout=emptyLayout();
ensureLayout(layout,sizes,annotations);
assert.deepEqual(annotations,original,'Legacy annotation coordinates remain unchanged');
assert.equal(layout.cards.a6.y,layout.pages[2].y+annotations[6].position.y);
layout.pages[1]={x:432,y:-300}; layout.cards.a0={x:-200,y:910};
ensureLayout(layout,sizes,annotations);
assert.deepEqual(layout.pages[1],{x:432,y:-300});
assert.deepEqual(layout.cards.a0,{x:-200,y:910});
layout.groups=[{id:'g1',name:'Evidence',members:['p:1','a:a0']}];
const before=structuredClone(layout), heights=new Map(annotations.map(a=>[a.id,650]));
arrangeLayout(layout,sizes,annotations,heights);
assert.ok(layout.pages[2].y>layout.cards.a4.y+650+100,'Next page clears the tallest comment column');
assert.equal(layout.cards.a2.y-layout.cards.a0.y,682);
assert.ok(layout.cards.a0.x<0 && layout.cards.a1.x>sizes[0].width);
assert.deepEqual(layout.groups,before.groups,'Rearrange preserves membership');
assert.deepEqual(readLayout(JSON.parse(JSON.stringify(layout))),layout);
const history=new LayoutHistory(); history.commit(before,layout);
assert.deepEqual(history.undo(layout),before); assert.deepEqual(history.redo(before),layout);
history.undo(layout); history.commit(before,{...before,snap:true}); assert.equal(history.canRedo,false);
assert.deepEqual(snappedDelta({x:0,y:0,width:100,height:100},{x:197,y:42},[{x:200,y:800,width:150,height:100}],8),{x:200,y:40});
for (const invalid of [null,{...layout,version:9},{...layout,pages:{1:{x:NaN,y:1}}},{...layout,groups:[{id:'g',name:'Bad',members:['p:1','p:1']}]},{...layout,groups:[{id:'g',name:'Bad',members:['g:nested']}]}]) assert.throws(()=>readLayout(invalid));
cleanLayout(layout,sizes,annotations.slice(1)); assert.equal(layout.cards.a0,undefined); assert.deepEqual(layout.groups[0].members,['p:1']);
console.log('PASS: canvas migration, mixed page sizes, measured spacing, group retention, undo/redo, snapping and malformed-layout protection');
